function register(app) {
  const serve = (name, type) => (req, res) => {
    res.setHeader('Content-Type', type);
    res.setHeader('Cache-Control', 'public, max-age=604800, immutable');
    fs.createReadStream(path.join(DIR, name)).on('error', () => res.status(404).end()).pipe(res);
  };
  app.get('/admin/assets/app.css', serve('app.css', 'text/css; charset=utf-8'));
  app.get('/admin/assets/app.js', serve('app.js', 'application/javascript; charset=utf-8'));
}

